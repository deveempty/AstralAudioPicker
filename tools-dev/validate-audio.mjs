import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultPayload = path.resolve(projectRoot, '..', '..', 'ARCHIVOS', 'AT', 'AT', '7 - AT')
const installedConfig = 'C:\\Program Files\\EqualizerAPO\\config'
const rootArgument = process.argv.find(argument => argument.startsWith('--root='))?.slice(7)
const payloadMode = process.argv.includes('--payload')
const payloadRoot = path.resolve(rootArgument || process.env.ASTRAL_AUDIO_CONFIG_ROOT || (payloadMode ? defaultPayload : installedConfig))
const manifestPath = path.join(projectRoot, 'audio-profile-schema', 'profile-map.json')
const errors = []
const warnings = []

const normalize = value => value.replaceAll('\\', '/').replace(/^\.\//, '').replace(/\/$/, '').toLowerCase()
const relative = value => path.relative(payloadRoot, value).replaceAll('\\', '/') || '.'
const exists = (relativePath, kind = 'any') => {
  const target = path.join(payloadRoot, ...relativePath.split('/'))
  if (!fs.existsSync(target)) return false
  if (kind === 'file') return fs.statSync(target).isFile()
  if (kind === 'directory') return fs.statSync(target).isDirectory()
  return true
}

function read(relativePath) {
  const target = path.join(payloadRoot, ...relativePath.split('/'))
  try {
    return fs.readFileSync(target, 'utf8').replace(/^\uFEFF/, '')
  } catch (error) {
    errors.push(`${relativePath}: cannot be read (${error.message})`)
    return ''
  }
}

function includesFrom(content) {
  return content.split(/\r?\n/).flatMap((line, index) => {
    const match = line.match(/^\s*(#\s*)?Include\s*:\s*(.*?)\s*$/i)
    return match ? [{ path: match[2], active: !match[1], line: index + 1 }] : []
  })
}

function validateIncludeTargets(file, content) {
  for (const include of includesFrom(content)) {
    const clean = include.path.trim().replace(/^['"]|['"]$/g, '')
    if (!clean || /[*?]/.test(clean) || path.isAbsolute(clean)) continue
    const target = path.resolve(payloadRoot, ...clean.replaceAll('\\', '/').split('/'))
    if (!target.toLowerCase().startsWith(`${payloadRoot.toLowerCase()}${path.sep}`)) {
      errors.push(`${file}:${include.line}: include escapes the payload root: ${include.path}`)
    } else if (!fs.existsSync(target)) {
      errors.push(`${file}:${include.line}: include target does not exist: ${include.path}`)
    }
  }
}

function walk(directory) {
  if (!fs.existsSync(directory)) return []
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const target = path.join(directory, entry.name)
    return entry.isDirectory() ? walk(target) : [target]
  })
}

function validateEqFile(file) {
  const content = fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '')
  const lines = content.split(/\r?\n/)
  const generated = lines.some(line => /^# Generated by Astral Audio Picker for\s+.+/i.test(line))
  const preamps = []
  const filters = []

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index].trim()
    if (!line) continue
    const preamp = line.match(/^#?\s*Preamp\s*:\s*(-?\d+(?:\.\d+)?)\s*dB$/i)
    if (preamp) { preamps.push(Number(preamp[1])); continue }
    if (line.startsWith('#')) continue
    const filter = line.match(/^Filter\s+(\d+)\s*:\s*ON\s+PK\s+Fc\s+(\d+(?:\.\d+)?)\s*Hz\s+Gain\s+(-?\d+(?:\.\d+)?)\s*dB\s+Q\s+(\d+(?:\.\d+)?)$/i)
    if (filter) {
      filters.push({ number: Number(filter[1]), frequency: Number(filter[2]), gain: Number(filter[3]), q: Number(filter[4]), line: index + 1 })
      continue
    }
    if (/^VSTPlugin\s*:\s*Library\s+"[^"]+"\s+.+$/i.test(line)) continue
    errors.push(`${relative(file)}:${index + 1}: unsupported EQ statement: ${line}`)
  }

  if (preamps.length !== 1) errors.push(`${relative(file)}: expected exactly one Preamp line`)
  if (preamps.some(value => !Number.isFinite(value) || value < -30 || value > 12)) errors.push(`${relative(file)}: Preamp is outside -30..12 dB`)
  const flatProfile = path.basename(file).toLowerCase() === 'flat.txt' || lines.some(line => /^# Headphone:\s*Flat\s*$/i.test(line))
  if (filters.length === 0 && !flatProfile) errors.push(`${relative(file)}: no PK filters found`)
  filters.forEach((filter, index) => {
    if (filter.number !== index + 1) errors.push(`${relative(file)}:${filter.line}: filters must be numbered sequentially from 1`)
    if (filter.frequency < 10 || filter.frequency > 24000) errors.push(`${relative(file)}:${filter.line}: frequency is outside 10..24000 Hz`)
    if (filter.gain < -30 || filter.gain > 30) errors.push(`${relative(file)}:${filter.line}: gain is outside -30..30 dB`)
    if (filter.q < 0.05 || filter.q > 30) errors.push(`${relative(file)}:${filter.line}: Q is outside 0.05..30`)
  })

  if (generated) {
    const requiredHeaders = ['# Target:', '# Headphone:', '# Source file:']
    for (const header of requiredHeaders) if (!lines.some(line => line.startsWith(header))) errors.push(`${relative(file)}: missing generated header ${header}`)
    const generatedHeaders = lines.filter(line => /^# (Generated by Astral Audio Picker for|Target:|Headphone:|Source file:)/i.test(line))
    if (generatedHeaders.length !== 4) errors.push(`${relative(file)}: generated EQ must contain the four required metadata comments`)
  }
}

if (!fs.existsSync(payloadRoot) || !fs.statSync(payloadRoot).isDirectory()) {
  errors.push(`Payload root was not found: ${payloadRoot}`)
} else {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  const requiredFiles = ['config.txt', 'at_v1.txt', 'at_v2.txt', 'aiw_v3.txt']
  requiredFiles.forEach(file => { if (!exists(file, 'file')) errors.push(`Required file is missing: ${file}`) })

  const expected = new Map([
    ['atV1', { target: 'v2', folder: 'data/eq/v2', include: 'at_v1.txt', channels: '7.1', endpoint: 'Cable Input 7.1' }],
    ['aiwV3', { target: 'v3', folder: 'data/eq/v3', include: 'aiw_v3.txt', channels: '7.1', endpoint: 'Cable Input 7.1' }],
    ['aiwV5', { target: 'v5', folder: 'data/eq/v5', include: null, channels: '16ch', endpoint: 'CABLE In 16ch' }],
  ])
  for (const [id, contract] of expected) {
    const profile = manifest.profiles?.find(candidate => candidate.id === id)
    if (!profile) { errors.push(`Profile manifest is missing ${id}`); continue }
    for (const [key, value] of Object.entries(contract)) if (profile[key === 'target' ? 'internalTarget' : key === 'folder' ? 'eqFolder' : key === 'include' ? 'includeFile' : key] !== value) errors.push(`Profile ${id} has an invalid ${key} mapping`)
    if (!exists(contract.folder, 'directory')) errors.push(`EQ folder is missing: ${contract.folder}`)
  }

  const config = read('config.txt')
  const configIncludes = includesFrom(config)
  for (const legacy of ['at_v1.txt', 'at_v2.txt', 'aiw_v3.txt']) if (!configIncludes.some(item => normalize(item.path) === legacy)) errors.push(`config.txt does not manage ${legacy}`)
  for (const folder of ['data/eq/v2', 'data/eq/v3', 'data/eq/v5']) {
    const owners = manifest.profiles.filter(profile => normalize(profile.eqFolder) === folder)
    if (owners.length !== 1) errors.push(`${folder} must belong to exactly one profile`)
  }
  if (!/^\s*Device\s*:\s*Cable Input 7\.1\s*$/im.test(config)) errors.push('config.txt is missing the legacy 7.1 device route')
  if (!/^\s*Device\s*:\s*CABLE In 16ch\s*$/im.test(config)) errors.push('config.txt is missing the V5 16ch device route')

  for (const file of requiredFiles) if (exists(file, 'file')) validateIncludeTargets(file, read(file))
  for (const folder of ['data/eq/v2', 'data/eq/v3', 'data/eq/v5']) {
    const files = walk(path.join(payloadRoot, ...folder.split('/'))).filter(file => file.toLowerCase().endsWith('.txt'))
    if (files.length === 0) warnings.push(`${folder}: empty base folder (allowed; AutoEQ can populate it later)`)
    files.forEach(validateEqFile)
  }
}

console.log(`Astral audio validation mode: ${payloadMode ? 'distribution payload' : 'installed Equalizer APO'}`)
console.log(`Astral audio validation root: ${payloadRoot}`)
warnings.forEach(message => console.warn(`WARN  ${message}`))
errors.forEach(message => console.error(`ERROR ${message}`))
if (errors.length) {
  console.error(`Audio validation failed with ${errors.length} error(s).`)
  process.exit(1)
}
console.log(`Audio validation passed with ${warnings.length} warning(s).`)
